def valid_email(value):
    return (
        len(value) <= 254
        and re.fullmatch(r"[^@\s]+@[^@\s]+\.[^@\s]+", value) is not None
    )


def send_password_reset_email(recipient, reset_url):
    sender = os.environ.get("GMAIL_ADDRESS", "").strip()
    app_password = os.environ.get("GMAIL_APP_PASSWORD", "").replace(" ", "")
    if not sender or not app_password:
        raise RuntimeError(
            "Gmail delivery is not configured. Set GMAIL_ADDRESS and "
            "GMAIL_APP_PASSWORD."
        )

    message = EmailMessage()
    message["Subject"] = "Reset your NovaVault password"
    message["From"] = sender
    message["To"] = recipient
    message.set_content(
        "We received a request to reset your NovaVault password.\n\n"
        f"Use this one-time link within 60 minutes:\n{reset_url}\n\n"
        "If you did not request this, you can ignore this email."
    )

    context = ssl.create_default_context()
    with smtplib.SMTP("smtp.gmail.com", 587, timeout=20) as server:
        server.ehlo()
        server.starttls(context=context)
        server.ehlo()
        server.login(sender, app_password)
        server.send_message(message)


def login_required(view):
    @wraps(view)
    def wrapped(*args, **kwargs):
        if not session.get("user_id"):
            flash("Please log in first.", "error")
            return redirect(url_for("login"))
        return view(*args, **kwargs)
    return wrapped


def csrf_token():
    if "_csrf_token" not in session:
        session["_csrf_token"] = secrets.token_urlsafe(32)
    return session["_csrf_token"]


@app.context_processor
def inject_helpers():
    return {"csrf_token": csrf_token}


@app.before_request
def check_csrf():
    if request.method == "POST":
        submitted = request.form.get("csrf_token", "")
        expected = session.get("_csrf_token", "")

        if not submitted or not expected or not hmac.compare_digest(
            submitted, expected
        ):
            abort(400, description="Invalid CSRF token. Reload the page.")


