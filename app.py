@contextmanager
def get_db():
    if DATABASE_URL:
        import psycopg
        from psycopg.rows import dict_row

        connection = psycopg.connect(
            DATABASE_URL,
            row_factory=dict_row,
            connect_timeout=10,
        )
        db = PostgresConnection(connection)
    else:
        connection = sqlite3.connect(DB_PATH, timeout=10)
        connection.row_factory = sqlite3.Row
        connection.execute("PRAGMA foreign_keys = ON")
        db = connection

    try:
        yield db
        connection.commit()
    except Exception:
        connection.rollback()
        raise
    finally:
        connection.close()


class PostgresConnection:
    def __init__(self, connection):
        self.connection = connection

    def execute(self, query, parameters=()):
        return self.connection.execute(query.replace("?", "%s"), parameters)


def init_db():
    if DATABASE_URL:
        user_table = """
            CREATE TABLE IF NOT EXISTS users (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                username VARCHAR(80) NOT NULL UNIQUE,
                password_hash TEXT NOT NULL,
                email VARCHAR(254)
            )
        """
        secrets_table = """
            CREATE TABLE IF NOT EXISTS secrets (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                user_id BIGINT NOT NULL,
                message TEXT NOT NULL,
                created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                FOREIGN KEY (user_id)
                    REFERENCES users(id) ON DELETE CASCADE
            )
        """
    else:
        user_table = """
            CREATE TABLE IF NOT EXISTS users (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                username TEXT NOT NULL UNIQUE,
                password_hash TEXT NOT NULL,
                email TEXT
            )
        """
        secrets_table = """
            CREATE TABLE IF NOT EXISTS secrets (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                user_id INTEGER NOT NULL,
                message TEXT NOT NULL,
                created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
                FOREIGN KEY (user_id)
                    REFERENCES users(id) ON DELETE CASCADE
            )
        """

    with get_db() as db:
        db.execute(user_table)
        if DATABASE_URL:
            db.execute("ALTER TABLE users ADD COLUMN IF NOT EXISTS email VARCHAR(254)")
        else:
            columns = {
                row["name"] for row in db.execute("PRAGMA table_info(users)")
            }
            if "email" not in columns:
                db.execute("ALTER TABLE users ADD COLUMN email TEXT")

        db.execute("""
            CREATE UNIQUE INDEX IF NOT EXISTS users_email_unique
            ON users(email) WHERE email IS NOT NULL
        """)
        db.execute(secrets_table)

        if DATABASE_URL:
            db.execute("""
                CREATE TABLE IF NOT EXISTS password_reset_tokens (
                    user_id BIGINT PRIMARY KEY,
                    token_hash TEXT NOT NULL,
                    expires_at BIGINT NOT NULL,
                    FOREIGN KEY (user_id)
                        REFERENCES users(id) ON DELETE CASCADE
                )
            """)
        else:
            db.execute("""
                CREATE TABLE IF NOT EXISTS password_reset_tokens (
                    user_id INTEGER PRIMARY KEY,
                    token_hash TEXT NOT NULL,
                    expires_at INTEGER NOT NULL,
                    FOREIGN KEY (user_id)
                        REFERENCES users(id) ON DELETE CASCADE
                )
            """)

        bootstrap_username = os.environ.get("BOOTSTRAP_USERNAME", "").strip()
        bootstrap_password = os.environ.get("BOOTSTRAP_PASSWORD", "")
        if bool(bootstrap_username) != bool(bootstrap_password):
            raise RuntimeError(
                "Set both BOOTSTRAP_USERNAME and BOOTSTRAP_PASSWORD, or neither."
            )
        if bootstrap_username and len(bootstrap_password) < 8:
            raise RuntimeError("BOOTSTRAP_PASSWORD must be at least 8 characters.")

        account = None
        if bootstrap_username:
            account = db.execute(
                "SELECT id FROM users WHERE username = ?",
                (bootstrap_username,),
            ).fetchone()

        if bootstrap_username and account is None:
            insert_sql = """
                INSERT INTO users (username, password_hash)
                VALUES (?, ?)
            """
            if DATABASE_URL:
                insert_sql += " RETURNING id"
            cursor = db.execute(
                insert_sql,
                (
                    bootstrap_username,
                    generate_password_hash(bootstrap_password),
                ),
            )
            user_id = (
                cursor.fetchone()["id"] if DATABASE_URL else cursor.lastrowid
            )

            db.execute(
                "INSERT INTO secrets (user_id, message) VALUES (?, ?)",
                (user_id, "Welcome to your NovaVault learning space."),
            )

